#!/usr/bin/env python3
"""Regenerates src/engine_cvar_help.inc from an oDFe source tree:  python3 tools/gen_engine_help.py <path to oDFe>

Pairs every Cvar_SetDescription(var, "text") with the Cvar_Get("name", ...) that assigned var."""
import glob, os, re, sys

root = sys.argv[1]
strlit = r'"(?:[^"\\]|\\.)*"'
get = re.compile(r'([A-Za-z_][\w\.\->\[\]]*)\s*=\s*(?:ri\.)?Cvar_Get\s*\(\s*"([^"]+)"')
desc = re.compile(r'Cvar_SetDescription\s*\(\s*([A-Za-z_][\w\.\->\[\]]*)\s*,\s*((?:' + strlit + r'\s*)+)\)')
desc2 = re.compile(
  r'Cvar_SetDescription\s*\(\s*(?:ri\.)?Cvar_Get\s*\(\s*"([^"]+)"[^;]*?\)\s*,\s*((?:' + strlit + r'\s*)+)\)', re.S)


def lit(x):
  return "".join(bytes(p[1:-1], "utf8").decode("unicode_escape") for p in re.findall(strlit, x))


def c(s):
  return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", " ") + '"'


out = {}
files = sorted(glob.glob(os.path.join(root, "code/**/*.c"), recursive=True),
               key=lambda f: ("/renderer2/" in f, "/renderervk/" in f, f))
for f in files:
  if any(d in f for d in ("/cgame/", "/game/", "/ui/", "/q3_ui/")):
    continue
  s = open(f, errors="replace").read()
  names = {}
  for m in get.finditer(s):
    names.setdefault(m.group(1), []).append((m.start(), m.group(2)))
  for m in desc2.finditer(s):
    out.setdefault(m.group(1), lit(m.group(2)))
  for m in desc.finditer(s):
    before = [n for p, n in names.get(m.group(1), []) if p < m.start()]
    if before:
      out.setdefault(before[-1], lit(m.group(2)))
    else:
      print("no Cvar_Get for", f, m.group(1))

rows = [
  "// Cvar descriptions of the oDFe engine (github.com/JBustos22/oDFe, code/**: Cvar_SetDescription), sorted by name.",
  "// A cgame cannot ask the engine for these, so search carries its own copy. Generated by tools/gen_engine_help.py.",
]
rows += ["  { %s, %s }," % (c(k), c(out[k])) for k in sorted(out, key=str.lower)]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "engine_cvar_help.inc"), "w").write("\n".join(rows) + "\n")
print(len(out), "descriptions")
